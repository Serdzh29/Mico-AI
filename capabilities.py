def link(phrase):
    return f'<a href="mico-do:{quote(phrase)}">{phrase}</a>'


def _categories(cfg=None):
    """Все функции стабильные: беты нет, пометок BETA и фильтра по каналам тоже нет."""
    yield from CATEGORIES


def html_capabilities(cfg=None):
    parts = ["<b>Вот что я умею.</b> Нажми на пример, и я выполню его:"]
    for cat, items in _categories(cfg):
        parts.append(f"<br>{heading(cat)}")
        parts += [f"<br>&nbsp;&nbsp;• {link(p)} — {what}" for p, what in items]
    parts.append("<br><br>Ещё: свои фразы-команды, кнопки под чатом. Чат открывается клавишей F8.")
    return "".join(parts)


def plain_capabilities(cfg=None):
    lines = ["Вот что я умею (нажми пример в чате или напиши его):"]
    for cat, items in _categories(cfg):
        lines.append(f"\n{cat}:")
        lines += [f"  • {p} — {what}" for p, what in items]
    return "\n".join(lines)


def html_tour():
    parts = ["<b>Привет! Я Mico AI 💛</b> Давай познакомимся. Нажми на пример, и я покажу, как это работает:"]
    for i, (title, text, phrase) in enumerate(TOUR, 1):
        parts.append(f"<br><br><b>{i}. {title}.</b> {text}<br>&nbsp;&nbsp;→ {link(phrase)}")
    parts.append("<br><br>Весь список возможностей — скажи «что ты умеешь». Знакомство можно повторить в меню.")
    return "".join(parts)
