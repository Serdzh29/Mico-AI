def link(phrase):
    return f'<a href="mico-do:{quote(phrase)}">{phrase}</a>'


def beta_mark(phrase):
    """Пометка BETA и кнопка «?» для бета-функций (пояснение открывает ссылка mico-info)."""
    key = BETA_PHRASES.get(phrase)
    if not key:
        return ""
    return (' <span style="color:#c0392b;font-weight:bold">BETA</span> '
            f'<a href="mico-info:{key}" style="text-decoration:none">❔</a>')


def _visible(phrase, cfg):
    """Бета-функции показываем только тем, у кого включён бета-канал."""
    key = BETA_PHRASES.get(phrase)
    return key is None or (cfg is not None and features.enabled(key, cfg))


def _categories(cfg):
    for cat, items in CATEGORIES:
        shown = [(p, w) for p, w in items if _visible(p, cfg)]
        if shown:
            yield cat, shown


def html_capabilities(cfg=None):
    parts = ["<b>Вот что я умею.</b> Нажми на пример, и я выполню его:"]
    for cat, items in _categories(cfg):
        parts.append(f"<br><b>{cat}</b>")
        parts += [f"<br>&nbsp;&nbsp;• {link(p)} — {what}{beta_mark(p)}" for p, what in items]
    parts.append("<br><br>Ещё: свои фразы-команды, кнопки под чатом и горячие клавиши (Ctrl+Alt+M, Ctrl+Alt+T).")
    return "".join(parts)


def plain_capabilities(cfg=None):
    lines = ["Вот что я умею (нажми пример в чате или напиши его):"]
    for cat, items in _categories(cfg):
        lines.append(f"\n{cat}:")
        lines += [f"  • {p} — {what}" for p, what in items]
    return "\n".join(lines)


def html_tour():
    parts = ["<b>Привет! Я Mico 💛</b> Давай познакомимся. Нажми на пример, и я покажу, как это работает:"]
    for i, (title, text, phrase) in enumerate(TOUR, 1):
        parts.append(f"<br><br><b>{i}. {title}.</b> {text}<br>&nbsp;&nbsp;→ {link(phrase)}")
    parts.append("<br><br>Весь список возможностей — скажи «что ты умеешь». Знакомство можно повторить в меню.")
    return "".join(parts)
