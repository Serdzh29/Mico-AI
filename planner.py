"""Многошаговые задачи: «подготовь рабочее место», «настрой, чтобы не отвлекало».
Модель составляет план из шагов, которые Mico AI уже умеет выполнять. Каждый шаг проверяется по белому списку.
Опасные шаги (выключение, удаление, сброс) в план не попадают — их нужно дать отдельной командой."""
import json, re

MAX_STEPS = 6

# Что разрешено в плане: начало шага должно совпадать с одним из шаблонов
ALLOWED = re.compile(
    r"^(открой|запусти|закрой|включи|выключи|громкост\w*|громче|тише|без звука|яркост\w*|ярче|темнее|"
    r"следующий трек|предыдущий трек|пауза|таймер|будильник|напомни|загугли|сверни все|"
    r"тёмн\w* тем\w*|светл\w* тем\w*|включи тёмную|включи светлую|скриншот|что на экране|не беспокоить|"
    r"проверь обновления|очисти кэш dns)\b", re.IGNORECASE)

# Опасное: такие шаги в план не берём
DANGER = re.compile(r"выключи (пк|компьютер|систему|windows)|перезагруз|спящ|сон\b|удали|сброс|сбрось|"
                    r"отформат|очисти корзин|выйди|выход|sfc|целостност|реестр|защитник|брандмауэр|служб|"
                    r"hyper|wsl|компонент|гибернац|заблокируй|блокировк", re.IGNORECASE)

TRIGGER = re.compile(r"^(подготовь|настрой|сделай так|сделай,? чтобы|собери|организуй|наладь)\b", re.IGNORECASE)

PROMPT = """Ты планируешь действия для помощника Mico AI на Windows. Ответь ТОЛЬКО JSON вида
{{"steps": ["шаг 1", "шаг 2"]}}
Каждый шаг — короткая команда по-русски из этих видов: «открой <программа или сайт>», «громкость <число>»,
«яркость <число>», «включи тёмную тему», «включи светлую тему», «таймер на <N> минут», «напомни через <N> минут <текст>»,
«следующий трек», «пауза», «сверни все окна», «не беспокоить», «скриншот», «что на экране», «проверь обновления».
Не больше {max} шагов. Не выключай компьютер, не удаляй файлы, не меняй системные настройки.

Задача: {task}"""


def wants_plan(text):
    return bool(TRIGGER.match((text or "").strip()))


def is_danger(step):
    return bool(DANGER.search(step or ""))


def parse_steps(raw):
    """Достаёт список шагов из ответа модели (даже если он обёрнут в текст или ```)."""
    m = re.search(r"\{.*\}", raw or "", re.DOTALL)
    if not m:
        raise ValueError("модель не вернула план")
    try:
        data = json.loads(m.group(0))
    except json.JSONDecodeError:
        raise ValueError("план не удалось прочитать")
    steps = data.get("steps")
    if not isinstance(steps, list):
        raise ValueError("в плане нет списка шагов")
    return [str(s).strip() for s in steps if isinstance(s, str) and s.strip()]


def check(steps):
    """(разрешённые шаги, отброшенные шаги с причиной)."""
    ok, dropped = [], []
    for s in steps:
        if is_danger(s):
            dropped.append((s, "опасное действие — дай его отдельной командой"))
        elif not ALLOWED.match(s):
            dropped.append((s, "не из списка действий, которые я выполняю в плане"))
        else:
            ok.append(s)
    return ok[:MAX_STEPS], dropped


def make_plan(task, ask_model):
    """ask_model(prompt) -> текст ответа модели. Возвращает (шаги, отброшенные)."""
    raw = ask_model(PROMPT.format(max=MAX_STEPS, task=task))
    return check(parse_steps(raw))
