def is_beta(name):
    return FEATURES.get(name, {}).get("stage") == "beta"


def channel(cfg):
    return cfg.get("update_channel", "stable")


def enabled(name, cfg):
    """Доступна ли функция в текущем канале."""
    if not is_beta(name):
        return True
    return channel(cfg) == "beta"


