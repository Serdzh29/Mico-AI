# Какие пункты настроек относятся к бета-функциям
SETTING_FEATURE = {"ini": "initiative"}


def is_beta(name):
    return FEATURES.get(name, {}).get("stage") == "beta"


def channel(cfg):
    """Стабильная сборка всегда на стабильном канале, бета-сборка — на том, что выбрал пользователь."""
    import version
    if version.BUILD_CHANNEL != "beta":
        return "stable"
    return cfg.get("update_channel", "stable")


def enabled(name, cfg):
    """Доступна ли функция в текущем канале."""
    if not is_beta(name):
        return True
    return channel(cfg) == "beta"


def explain(name):
    f = FEATURES[name]
    return f"{f['title']} — BETA\n\n{f['explain']}\n\n{DEV_NOTE}"
