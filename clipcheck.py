"""Проверка текста из буфера обмена: исправить орфографию и грамматику. Чистая логика, без Qt.
Команды: «исправь текст из буфера», «проверь буфер». Перевода здесь нет: он удалён из проекта.
Текст из буфера уходит только локальной модели и не сохраняется. Пароли и номера карт не обрабатываем."""
import re

MAX_CHARS = 3000

CMD = re.compile(r"^(?P<verb>исправь|проверь|поправь)\s+(?:текст\s+|то\s+)?"
                 r"(?:из\s+|в\s+|с\s+)?(?:буфер\w*|копи\w*)(?:\s+обмена)?\W*$")


def command(q):
    """None — это не команда для буфера. Иначе {'action': 'fix'}."""
    return {"action": "fix"} if CMD.match((q or "").strip().lower()) else None


def prompt(cc, text):
    """Текст для модели: вернуть только исправленный вариант, без пояснений."""
    return ("Исправь орфографию, пунктуацию и грамматику в тексте ниже. Сохрани смысл и стиль. "
            "Верни только исправленный текст, без пояснений.\n\nТекст:\n" + text[:MAX_CHARS])
