def norm(text):
    """Приводит фразу к виду для сравнения: без регистра, «ё» → «е», числа → «#», без знаков и слов-паразитов."""
    t = (text or "").lower().replace("ё", "е")
    t = re.sub(r"\d+", " # ", t)
    t = re.sub(r"[^\w#\s\-.]", " ", t)
    return " ".join(w.strip(".-") for w in t.split() if w.strip(".-") and w not in FILLER)


def actions(text):
    acts = set()
    for w in text.split():
        forms = {w, w[2:]} if w.startswith("по") and len(w) > 5 else {w}      # «потише» → «тише»
        for name, roots in ACTION_ROOTS.items():
            if any(f.startswith(r) for f in forms for r in roots):
                acts.add(name)
    return frozenset(acts)


def _grams(text):
    out = Counter()
    for w in text.split():
        w = f" {w} "
        for i in range(len(w) - 2):
            out[w[i:i + 3]] += 1
    return out


def _cos(a, b):
    common = set(a) & set(b)
    num = sum(a[k] * b[k] for k in common)
    den = (sum(v * v for v in a.values()) ** 0.5) * (sum(v * v for v in b.values()) ** 0.5)
    return num / den if den else 0.0


_INDEX = None


def _index():
    global _INDEX
    if _INDEX is None:
        rows = []
        for canon, variants in CATALOG:
            for v in variants:
                nv = norm(v)
                rows.append((nv, canon, actions(nv), _grams(nv)))
        _INDEX = rows
    return _INDEX


def _fill(canon, nums):
    if canon.count("#") != len(nums):
        return None
    out = canon
    for n in nums:
        out = out.replace("#", n, 1)
    return out


def match(q):
    """Известная команда, на которую похожа фраза, или None. Ничего не угадываем, если не уверены."""
    text = norm(q)
    if len(text.replace("#", "").strip()) < 4:
        return None
    if NEG.search(text) or QUESTION.search(text):
        return None
    acts, vec = actions(text), _grams(text)
    scored = []
    for nv, canon, v_acts, v_vec in _index():
        if v_acts != acts or nv.count("#") != text.count("#"):
            continue
        scored.append((_cos(vec, v_vec), canon))
    if not scored:
        return None
    scored.sort(reverse=True)
    best, canon = scored[0]
    if best < MIN_SCORE:
        return None
    rivals = [s for s, c in scored if c != canon]
    if rivals and best - max(rivals) < MARGIN:
        return None
    return _fill(canon, re.findall(r"\d+", (q or "").lower().replace("ё", "е")))


def all_canonical():
    """Каноны с примером числа — чтобы проверять, что каждый понимают правила."""
    return [(canon, _fill(canon, ["5"] * canon.count("#"))) for canon, _ in CATALOG]
