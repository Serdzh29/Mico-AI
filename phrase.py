"""Понимание фраз не по шаблону. Ничего не меняет по смыслу: убирает эмодзи и знаки препинания,
обращение «Мико» и вежливые слова, приводит разговорные синонимы к формам, которые команды уже понимают.
Также распознаёт приветствия и варианты помодоро."""
import random
import re
import time

EMOJI = re.compile("[\U0001F000-\U0001FAFF\u2600-\u27BF\u2B00-\u2BFF\uFE0F\u200d\u2190-\u21FF]+")
ADDRESS = re.compile(r"^\s*(?:эй|слушай|ну|мико|mico)\s*[,!.:;?]*\s*(?=\S)", re.IGNORECASE)
FILLERS = re.compile(r"\b(?:пожалуйста|будь\s+добр[аоы]?|можешь|можете|мне|ну|короче|слушай|плиз|please|"
                     r"ладно|окей|ок)\b", re.IGNORECASE)
PUNCT = re.compile(r"[!?;,«»\"'()\[\]{}…*~_]+")

# разговорные синонимы → формы, которые команды уже понимают
SYNONYMS = [
    (r"\b(?:погромче|прибавь\s+звук|прибавь\s+громкость|увеличь\s+громкость|добавь\s+громкость|"
     r"громкость\s+побольше|звук\s+побольше|сделай\s+громче|звук\s+громче|громче\s+звук)\b", "громче"),
    (r"\b(?:потише|убавь\s+звук|убавь\s+громкость|уменьши\s+громкость|громкость\s+поменьше|"
     r"звук\s+поменьше|сделай\s+тише|звук\s+тише|тише\s+звук)\b", "тише"),
    (r"\b(?:выруби\s+звук|убери\s+звук|заглуши\s+звук|выключи\s+звук|отключи\s+звук|выруби\s+громкость|"
     r"звук\s+выключи|без\s+звуковой)\b", "без звука"),
    (r"\b(?:поярче|прибавь\s+яркость|увеличь\s+яркость|добавь\s+яркость|яркость\s+побольше|сделай\s+ярче)\b", "ярче"),
    (r"\b(?:потемнее|убавь\s+яркость|уменьши\s+яркость|яркость\s+поменьше|сделай\s+темнее|приглуши\s+экран)\b",
     "темнее"),
    (r"\b(?:засеки|поставь\s+таймер|запусти\s+таймер|включи\s+таймер|сделай\s+таймер|создай\s+таймер)\s+",
     "таймер "),
    (r"\b(?:залочи|лочи|заблокируй)(?:\s+(?:комп\w*|пк|ноут\w*|экран|компьютер))?\b", "заблокируй пк"),
]
_SYN = [(re.compile(p, re.IGNORECASE), r) for p, r in SYNONYMS]


def clean(text):
    """Убираем эмодзи, обращение, знаки и вежливые слова. Регистр сохраняем."""
    t = EMOJI.sub(" ", text or "")
    t = re.sub(r"(\w+)-ка\b", r"\1", t, flags=re.IGNORECASE)     # «давай-ка» → «давай»
    t = ADDRESS.sub("", t)
    t = PUNCT.sub(" ", t)
    t = FILLERS.sub(" ", t)
    return re.sub(r"\s+", " ", t).strip()


def canonical(text):
    """Текст с известными формами команд; то, что уже понятно, не трогаем."""
    t = clean(text)
    for rx, repl in _SYN:
        t = rx.sub(repl, t)
    return re.sub(r"\s+", " ", t).strip()


# ---------- приветствия ----------
GREETING_RE = re.compile(
    r"^(?:привет|приветик|здравствуй|здравствуйте|здарова|хай|хей|хеллоу|хелло|hi|hello|hey|салют|"
    r"добрый\s+день|добрый\s+вечер|доброе\s+утро|доброй\s+ночи|доброго\s+времени\s+суток|добрейшего\s+дня)"
    r"(?:\s+(?:мико|mico|друг|дружище|подруга))?$", re.IGNORECASE)


def is_greeting(text):
    return bool(GREETING_RE.match(clean(text).lower()))


GREETINGS = {
    "morning": ["Доброе утро! ☀️", "Доброе утро! 🌅", "Доброе утро! ☕ Как спалось?",
                "Доброе утро! Хорошего начала дня ✨"],
    "day": ["Добрый день! ☀️", "Добрый день! 😊", "Добрый день! Как дела? 🙂"],
    "evening": ["Добрый вечер! 🌙", "Добрый вечер! ✨", "Добрый вечер! Как прошёл день? 🌆"],
    "night": ["Доброй ночи! 🌙", "Доброй ночи! 😴", "Не спится? Доброй ночи! 🌌"],
}


def period(now=None):
    h = time.localtime(now or time.time()).tm_hour
    if 5 <= h < 11:
        return "morning"
    if 11 <= h < 17:
        return "day"
    if 17 <= h < 23:
        return "evening"
    return "night"


def greeting_kind(text):
    """Какое время суток назвал пользователь: «доброе утро» → morning; иначе None (берём текущее время)."""
    t = clean(text).lower()
    if re.search(r"утр", t):
        return "morning"
    if re.search(r"\bдень\b|днем|днём", t):
        return "day"
    if re.search(r"вечер", t):
        return "evening"
    if re.search(r"ноч", t):
        return "night"
    return None


def greeting_text(now=None, kind=None):
    return random.choice(GREETINGS[kind or period(now)])


# ---------- помодоро ----------
_START_VERBS = r"(?:давай|начни|начинай|запусти|включи|стартуй|старт|хочу|сделай|поставь|нужно|надо|запускай)"
_DURATION = r"(?:на\s+(?:25|двадцать\s+пять)\s+минут\w*|сейчас)"


def pomodoro_intent(text):
    """'start' | 'stop' | 'status' | None — понимает помодоро в любой форме."""
    t = clean(text).lower()
    if not re.search(r"помодоро|помидор|pomodoro|рабоч\w+\s+цикл|сессию\s+работы|сессия\s+работы", t):
        return None
    if re.search(r"сколько|сегодня|статистик|итог|сделал|прошло", t):
        return "status"
    if re.search(r"\b(?:стоп|останови\w*|отмен\w*|выключи|выруби|прекрати|хватит|закончи|заверши\w*|отмени)\b", t):
        return "stop"
    rest = re.sub(r"\b" + _START_VERBS + r"\b", " ", t)
    rest = re.sub(_DURATION, " ", rest)
    rest = re.sub(r"\b(?:режим|рабочий|рабочая|мой|моё|мое|цикл|сессию|сессия|работы|таймер)\b", " ", rest)
    rest = re.sub(r"помодоро|помидор\w*|pomodoro", " ", rest)
    if re.sub(r"\s+", "", rest) == "":
        return "start"
    return None
