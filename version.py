def normalize(v):
    """Один вид записи: «2026.10.1305a», «v2026.10.1305 (a)», «2026.10.1305(a)» → «2026.10.1305(a)».
    Буква — срочное исправление после выпуска 1305 (a, b, c…). Без буквы номер не меняется."""
    s = str(v).strip().lstrip("vV").replace(" бета", "").strip()
    m = re.fullmatch(r"(\d{4}\.\d{2}\.\d{4})\s*\(?([a-z])\)?", s)
    return f"{m.group(1)}({m.group(2)})" if m else s


def _vt(v):
    """Ключ для сравнения выпусков.
    Старые номера: «3.29» и «29» → (29,). Даты: «2026.10.12» → (2026, 10, 12, 0),
    «2026.10.1201» → (2026, 10, 12, 1). Срочное исправление с буквой добавляет номер буквы:
    «2026.10.1305(a)» → (2026, 10, 13, 5, 1), то есть новее 1305 и старше 1306."""
    s = normalize(v).replace(" бета", "").strip()          # приписка «бета» не влияет на порядок
    letter = None
    m = re.fullmatch(r"(\d{4}\.\d{2}\.\d{4})\(([a-z])\)", s)
    if m:
        s, letter = m.group(1), m.group(2)
    if s.isdigit() or s.startswith("3."):
        return (int(s.split(".")[-1]),)
    y, mm, rest = s.split(".")
    key = (int(y), int(mm), int(rest[:2]), int(rest[2:] or 0))
    if letter:
        key += (ord(letter) - ord("a") + 1,)
    return key


def display_version(channel="stable"):
    """Номер для показа: на бета-канале с припиской «бета», на стабильном — только число."""
    return APP_VERSION + (" бета" if channel == "beta" else "")


def _label(v):
    """Как показать номер пользователю: «3.29» → «29», даты — как есть."""
    s = str(v).strip()
    return s if s.count(".") == 2 and not s.startswith("3.") else str(_vt(s)[0])


def whats_new(prev):
    """Текст о изменениях между prev и APP_VERSION или '' если менять нечего."""
    versions = [v for v in CHANGELOG if _vt(prev) < _vt(v) <= _vt(APP_VERSION)]
    if not versions:
        return ""
    lines = [f"🆕 Mico обновился: {_label(prev)} → {_label(APP_VERSION)}."]
    tries = []
    for v in versions:
        lines.append(f"\nВерсия {v}:")
        lines += [f"• {c}" for c in CHANGELOG[v]["changes"]]
        tries += CHANGELOG[v]["try"]
    lines.append("\nХочешь проверить новое? Попробуй, например:")
    lines += [f"• «{t}»" for t in tries[:5]]
    lines.append("Напиши мне, что сработало, а что нет.")
    return "\n".join(lines)


def recent_changes(n=3):
    """Текст последних n выпусков для меню «📜 Что нового»."""
    keys = sorted(CHANGELOG, key=_vt, reverse=True)[:n]
    lines = []
    for k in keys:
        lines.append(f"Версия {k}:")
        lines += [f"  • {c}" for c in CHANGELOG[k]["changes"]]
    return "\n".join(lines)
