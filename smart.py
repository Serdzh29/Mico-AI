def capability_question(ql):
    q = ql.strip(" ?!.")
    if re.search(r"\b(умеешь|можешь)\b", q) and not is_toggle_question(q):
        if re.search(r"^(а\s+)?(ты\s+)?(умеешь|можешь)(\s+ли)?\s+", q):
            return ("Попробуй просто сказать, что нужно, например «включи музыку», «открой ютуб» или «таймер на 10 минут». "
                    "Полный список — «что ты умеешь?».")
    return None


