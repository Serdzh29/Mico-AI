def smalltalk(ql):
    """Reply-подобный кортеж (текст, настроение) или None."""
    from phrase import clean                       # эмодзи и знаки не мешают: «ты молодец 😊»
    t = clean(ql).strip(" ?!.").lower().replace("ё", "е")
    if _CRISIS.search(t):
        return ("Мне важно, что ты это написал. Пожалуйста, расскажи об этом близкому человеку прямо сейчас "
                "или позвони в экстренную службу — 112. Если хочется поговорить, я рядом, слушаю.", "worried")
    if _THANKS.match(t):
        return (random.choice(["Пожалуйста! 💛", "Всегда рад помочь 😊", "Обращайся! ✨"]), "happy")
    if _PRAISE.match(t):
        return (random.choice(["Спасибо! Стараюсь 😊", "Спасибо, мне приятно 💛", "Ты тоже молодец! ✨"]), "proud")
    if _SAD.match(t):
        return ("Мне жаль, что тебе так. Если хочешь, расскажи, что случилось, я выслушаю. "
                "Если совсем тяжело, поговори с кем-то из близких.", "sad")
    return None
