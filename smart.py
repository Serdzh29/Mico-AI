def bare_verb_question(ql):
    """«выключи» без объекта → уточняем, а не отправляем в модель."""
    t = ql.strip(" ?!.").lower().replace("ё", "е")
    if t in _BARE_VERBS:
        infinitive = _BARE_VERBS[t]
        return f"Что именно {infinitive}? Например: {_BARE_EXAMPLE[infinitive]}."
    return None


