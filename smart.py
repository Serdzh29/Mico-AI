def _category(name):
    low = name.lower().replace("ё", "е")
    for title, keys in CATEGORIES:
        if any(k.replace("ё", "е") in low for k in keys):
            return title
    return "Прочее"


def toggles_overview(toggles):
    """Ответ «какие настройки ты умеешь переключать»: по разделам, с примерами."""
    groups = {}
    for t in toggles:
        groups.setdefault(_category(t.name), []).append(t.name)
    order = [c for c, _ in CATEGORIES] + ["Прочее"]
    lines = [f"Я умею переключать {len(toggles)} настроек Windows и компонентов. По разделам:"]
    for title in order:
        names = groups.get(title)
        if not names:
            continue
        shown = ", ".join(sorted(names)[:5])
        more = f" и ещё {len(names) - 5}" if len(names) > 5 else ""
        lines.append(f"• {title}: {shown}{more}")
    lines.append("Скажи, например: «выключи Wi-Fi», «включи ночной свет» или «отключи гибернацию».")
    return "\n".join(lines)


def is_toggle_question(ql):
    return bool(re.search(r"какие\s+(настройки|переключател\w*|компоненты|функции)|что\s+(ты\s+)?"
                          r"(умеешь|можешь)\s+(переключать|выключать|включать|менять)|"
                          r"что\s+можно\s+(переключить|выключить|включить)", ql))


